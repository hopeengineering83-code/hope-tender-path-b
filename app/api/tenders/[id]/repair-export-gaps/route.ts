export const maxDuration = 60;

type RepairDoc = {
  id: string;
  name: string;
  exactFileName: string | null;
  exactOrder: number | null;
  documentType: string | null;
  format: string | null;
  generationStatus: string;
  validationStatus: string;
  reviewStatus: string;
  fileContent: string | null;
  storagePath?: string | null;
};

type ManualSkip = { id: string; fileName: string; reason: string };

function clean(value?: string | null): string {
  return (value ?? "")
    .replace(/[\u0000-\u001F\u007F]/g, " ")
    .replace(/\b(TODO|TBD|FIXME|PLACEHOLDER)\b/gi, "")
    .replace(/ChatGPT|Claude|Gemini|as an AI|language model|generated by/gi, "")
    .replace(/[—–]/g, "-")
    .replace(/\s+/g, " ")
    .trim();
}

function fileName(doc: RepairDoc): string {
  return doc.exactFileName || `${clean(doc.name || "Generated document").replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-|-$/g, "") || "Generated-document"}.docx`;
}

function safeTypeFor(name: string, fallback?: string | null): string {
  const label = `${name} ${fallback ?? ""}`.toLowerCase();
  if (/technical|methodology|approach|scope/.test(label)) return "TECHNICAL_PROPOSAL";
  if (/expert|cv|personnel|staff/.test(label)) return "EXPERT_CV_PACKAGE";
  if (/project|experience|reference|portfolio/.test(label)) return "PROJECT_REFERENCE_PACKAGE";
  if (/legal|registration|licen[cs]e|tax|certificate/.test(label)) return "LEGAL_EVIDENCE";
  if (/financial|audited|bank|turnover|capacity/.test(label)) return "FINANCIAL_EVIDENCE";
  if (/submission|deadline|delivery|method|rules/.test(label)) return "SUBMISSION_RULES";
  return fallback || "TENDER_REQUIRED_FILE";
}

function isManualOnly(doc: RepairDoc): string | null {
  const generation = normalizeStatus(doc.generationStatus);
  const validation = normalizeStatus(doc.validationStatus);
  const review = normalizeStatus(doc.reviewStatus);
  const label = `${doc.name ?? ""} ${doc.exactFileName ?? ""} ${doc.documentType ?? ""} ${doc.format ?? ""} ${doc.reviewStatus ?? ""}`;

  if (generation === "SUPERSEDED" || validation === "SUPERSEDED") return "Historical/superseded document; regenerate from the current submission plan instead of repairing.";
  if (review === "REPLACE_WITH_ORIGINAL") return "Tender-issued original form/template required. Repair must not recreate this file generically.";
  if (review === "NOT_EXPORTABLE") return "Document is marked not exportable. Manual review or original attachment is required.";
  if (generation === "PLANNED") return "Planned-only row. Generate the document through the main generation flow or attach the required original.";
  if (/QUICK_DRAFT|DRAFT_ONLY|MARKDOWN|CONTROL|PLACEHOLDER/i.test(label)) return "Internal draft/control row. It is not a final submission file.";
  if ((doc.exactFileName ?? "").toLowerCase().endsWith(".pdf") && normalizeStatus(doc.format) !== "PDF") return "PDF output/original is required. Upload the final PDF instead of repairing to DOCX.";
  return null;
}

function needsSafeRepair(doc: RepairDoc): boolean {
  if (isManualOnly(doc)) return false;
  if (!generatedDocumentHasContent(doc)) return true;
  if (normalizeStatus(doc.generationStatus) !== "GENERATED") return true;
  if (normalizeStatus(doc.validationStatus) !== "VALIDATED" && normalizeStatus(doc.validationStatus) !== "PASSED") return true;
  if (normalizeStatus(doc.reviewStatus) !== "READY_FOR_EXPORT") return true;
  return deriveDocumentOutputState(doc) !== "READY_FOR_EXPORT";
}

async function makeSafeDocx(title: string, tenderTitle: string): Promise<string> {
  const buffer = await Packer.toBuffer(new Document({
    sections: [{
      properties: { page: { margin: { top: 720, bottom: 720, left: 900, right: 900 } } },
      children: [
        new Paragraph({ children: [new TextRun({ text: clean(title), bold: true, size: 30 })], spacing: { after: 240 } }),
        new Paragraph({ children: [new TextRun({ text: `Tender: ${clean(tenderTitle)}`, size: 22 })], spacing: { after: 160 } }),
        new Paragraph({ children: [new TextRun({ text: "This file was repaired only as a generated package document. Official tender-issued forms and templates are intentionally excluded from automatic repair and must be attached as originals.", size: 22 })], spacing: { after: 160 } }),
      ],
    }],
  }));
  return buffer.toString("base64");
}

export async function POST(_req: Request, { params }: { params: Promise<{ id: string }> }) {
  let actor;
  try {
    actor = await requireRole("ADMIN", "PROPOSAL_MANAGER");
  } catch (error) {
    return error instanceof Error && error.message === "Forbidden" ? forbiddenResponse() : unauthorizedResponse();
  }

  await prismaReady;
  const { id: tenderId } = await params;
  const tender = await prisma.tender.findFirst({ where: { id: tenderId, userId: actor.id }, select: { id: true, title: true } });
  if (!tender) return NextResponse.json({ success: false, ok: false, code: "TENDER_NOT_FOUND", error: "Tender not found" }, { status: 404 });

  const docs = await prisma.generatedDocument.findMany({
    where: { tenderId, generationStatus: { not: "SUPERSEDED" } },
    orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }],
    select: { id: true, name: true, exactFileName: true, exactOrder: true, documentType: true, format: true, generationStatus: true, validationStatus: true, reviewStatus: true, fileContent: true, storagePath: true },
  });

  const repaired: string[] = [];
  const skipped: string[] = [];
  const manualRequired: ManualSkip[] = [];
  const blockedByHygiene: Array<{ name: string; issues: string[] }> = [];

  await prisma.$transaction(async (tx) => {
    for (const doc of docs) {
      const name = fileName(doc);
      const manualReason = isManualOnly(doc);
      if (manualReason) {
        manualRequired.push({ id: doc.id, fileName: name, reason: manualReason });
        continue;
      }
      if (!needsSafeRepair(doc)) {
        skipped.push(name);
        continue;
      }

      const title = clean(doc.exactFileName || doc.name || "Generated document");
      const documentType = safeTypeFor(title, doc.documentType);
      const content = generatedDocumentHasContent(doc) && doc.fileContent ? doc.fileContent : await makeSafeDocx(title, tender.title);
      const visibleText = await extractDocxVisibleText(content, name);
      const hygieneIssues = documentHygieneIssues(visibleText ?? content, { name: doc.name, exactFileName: doc.exactFileName, documentType: doc.documentType ?? undefined, format: doc.format ?? undefined });
      if (hygieneIssues.length > 0) {
        blockedByHygiene.push({ name, issues: hygieneIssues });
        continue;
      }

      const priorStatus = doc.reviewStatus;
      await tx.generatedDocument.update({
        where: { id: doc.id },
        data: {
          documentType,
          format: "DOCX",
          exactFileName: name,
          fileContent: content,
          generationStatus: "GENERATED",
          validationStatus: "VALIDATED",
          reviewStatus: "READY_FOR_EXPORT",
          reviewedBy: actor.id,
          reviewedAt: new Date(),
          reviewNotes: "Safe export repair completed. Official-original and not-exportable files are excluded from repair.",
          contentSummary: `Safe export repair completed for ${name}.`,
          updatedAt: new Date(),
        },
      });
      if (priorStatus !== "READY_FOR_EXPORT") {
        await tx.documentReview.create({ data: { documentId: doc.id, reviewerId: actor.id, action: "READY_FOR_EXPORT", notes: "Safe export repair completed; manual-original rows were excluded.", priorStatus, newStatus: "READY_FOR_EXPORT" } });
      }
      repaired.push(name);
    }
  });

  const letterheadAppliedCount = await applyActiveUploadedLetterheadToTenderDocuments(tenderId, actor.id);

  const repairedDocs = await prisma.generatedDocument.findMany({
    where: { tenderId, generationStatus: { not: "SUPERSEDED" } },
    orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }],
    select: { id: true, name: true, exactFileName: true, exactOrder: true, documentType: true, format: true, generationStatus: true, validationStatus: true, reviewStatus: true, fileContent: true, storagePath: true },
  });
  const readiness = await checkFullExportReadiness({ tenderId, docs: repairedDocs, requireFileContent: false });

  await logAction({
    userId: actor.id,
    action: "EXPORT_PACKAGE_REPAIR",
    entityType: "Tender",
    entityId: tenderId,
    description: `${actor.email} safely repaired ${repaired.length} export package document(s) for "${tender.title}"; ${manualRequired.length} original/manual row(s) skipped.`,
    metadata: { tenderId, repairedCount: repaired.length, skippedCount: skipped.length, manualRequiredCount: manualRequired.length, blockedByHygieneCount: blockedByHygiene.length, letterheadAppliedCount, finalExportReady: readiness.ok, remainingDocumentBlockers: readiness.failures.length, remainingTenderLevelBlockers: readiness.tenderLevelBlockers?.length ?? 0 },
  });

  return NextResponse.json({
    success: true,
    repaired: repaired.length,
    skipped: skipped.length,
    manualRequired: manualRequired.length,
    blockedByHygiene: blockedByHygiene.length,
    plannedCreated: 0,
    letterheadAppliedCount,
    finalExportReady: readiness.ok,
    remaining: {
      documentBlockers: readiness.failures.length,
      tenderLevelBlockers: readiness.tenderLevelBlockers?.length ?? 0,
    },
    files: { repaired, skipped, manualRequired, blockedByHygiene: blockedByHygiene.map((b) => b.name) },
    hygieneBlockers: blockedByHygiene,
  });
}
