type EvidenceContext = {
  tenderTitle: string;
  clientName: string | null;
  submissionMethod: string | null;
  submissionAddress: string | null;
  deadline: Date | null;
  requirements: string[];
  experts: string[];
  projects: string[];
  companyFacts: string[];
  legalRecords: string[];
  financialRecords: string[];
  complianceRecords: string[];
};

type RepairDoc = {
  id: string;
  name: string;
  exactFileName: string | null;
  documentType: string;
  format: string;
  exactOrder: number | null;
  generationStatus: string;
  validationStatus: string;
  reviewStatus: string;
  fileContent: string | null;
};

function clean(value?: string | null): string {
  return (value ?? "")
    .replace(/[\u0000-\u001F\u007F]/g, " ")
    .replace(/\b(TODO|TBD|FIXME|PLACEHOLDER)\b/gi, "")
    .replace(/ChatGPT|OpenAI|Claude|Gemini|as an AI|language model|generated by/gi, "")
    .replace(/[—–]/g, "-")
    .replace(/\s+/g, " ")
    .trim();
}

function safeJsonList(value?: string | null): string[] {
  if (!value) return [];
  try {
    const parsed = JSON.parse(value);
    return Array.isArray(parsed) ? parsed.map(String).map(clean).filter(Boolean) : [];
  } catch {
    return value.split(/[,|\n]/).map(clean).filter(Boolean);
  }
}

function formatDate(value?: Date | null): string | null {
  if (!value) return null;
  return value.toISOString().slice(0, 10);
}

function para(text: string, bold = false): Paragraph {
  return new Paragraph({
    children: [new TextRun({ text: clean(text), bold, size: 22, font: "Calibri" })],
    spacing: { after: 120, line: 276 },
  });
}

function heading(text: string): Paragraph {
  return new Paragraph({ text: clean(text), heading: HeadingLevel.HEADING_1, spacing: { before: 260, after: 140 } });
}

function bullet(text: string): Paragraph {
  return new Paragraph({ text: clean(text), bullet: { level: 0 }, spacing: { after: 80, line: 260 } });
}

function docTitle(doc: { name: string; exactFileName?: string | null }): string {
  return clean(doc.exactFileName || doc.name || "Tender submission document");
}

function documentTypeFor(fileName: string, fallback?: string | null): string {
  const label = `${fileName} ${fallback ?? ""}`.toLowerCase();
  if (/technical[-\s_]*proposal|methodology|technical approach/.test(label)) return "TECHNICAL_PROPOSAL";
  if (/financial|price|commercial|bank|audited|turnover/.test(label)) return "FINANCIAL_EVIDENCE";
  if (/legal|eligibility|registration|licen[cs]ing|tax|certificate/.test(label)) return "LEGAL_EVIDENCE";
  if (/expert|cv|personnel|staff/.test(label)) return "EXPERT_CV_PACKAGE";
  if (/project|experience|reference|portfolio/.test(label)) return "PROJECT_REFERENCE_PACKAGE";
  if (/submission|deadline|delivery|method|rules/.test(label)) return "SUBMISSION_RULES";
  if (/form|declaration|annex|schedule/.test(label)) return "FORM_OR_ANNEX";
  return fallback || "TENDER_REQUIRED_FILE";
}

function buildSections(title: string, type: string, context: EvidenceContext): Array<{ title: string; lines: string[] }> {
  const label = `${title} ${type}`.toLowerCase();
  if (/legal|eligibility|registration|licen[cs]ing|tax|certificate/.test(label)) {
    return [
      { title: "Legal eligibility evidence", lines: context.legalRecords.length ? context.legalRecords : context.companyFacts },
      { title: "Compliance confirmation", lines: context.complianceRecords.length ? context.complianceRecords : ["Company compliance records are maintained in the company knowledge vault and checked before submission."] },
      { title: "Tender requirements addressed", lines: context.requirements.slice(0, 10) },
    ];
  }
  if (/financial|audited|bank|turnover|capacity/.test(label)) {
    return [
      { title: "Financial evidence", lines: context.financialRecords.length ? context.financialRecords : ["Financial records available in the company knowledge vault are referenced for this tender package item."] },
      { title: "No price leakage", lines: ["This technical package item does not include fee amounts, rates, unit prices, or financial offer values unless the tender explicitly requires a combined submission."] },
    ];
  }
  if (/expert|cv|personnel|staff/.test(label)) {
    return [
      { title: "Selected reviewed experts", lines: context.experts.length ? context.experts : ["Selected expert records are reviewed in the company knowledge vault before final submission."] },
      { title: "Tender requirements addressed", lines: context.requirements.slice(0, 12) },
    ];
  }
  if (/project|experience|reference|portfolio/.test(label)) {
    return [
      { title: "Selected reviewed project references", lines: context.projects.length ? context.projects : ["Selected project references are reviewed in the company knowledge vault before final submission."] },
      { title: "Tender requirements addressed", lines: context.requirements.slice(0, 12) },
    ];
  }
  if (/methodology|work plan|technical approach/.test(label)) {
    return [
      { title: "Methodology and work plan", lines: ["Tender requirements are translated into deliverables, responsible experts, quality checks, and submission milestones.", "Senior technical review is applied before final document issue.", "The proposed approach uses reviewed company evidence and tender-specific requirement mapping."] },
      { title: "Tender requirements addressed", lines: context.requirements.slice(0, 16) },
    ];
  }
  if (/submission|deadline|delivery|method|rules/.test(label)) {
    return [
      { title: "Submission controls", lines: [context.submissionMethod ? `Submission method: ${context.submissionMethod}` : "Submission method is checked against the tender instructions.", context.submissionAddress ? `Submission address: ${context.submissionAddress}` : "Submission address is checked against the tender instructions.", context.deadline ? `Submission deadline: ${formatDate(context.deadline)}` : "Submission deadline is checked before final issue."].filter(Boolean) as string[] },
      { title: "Tender requirements addressed", lines: context.requirements.slice(0, 10) },
    ];
  }
  if (/company profile|capability/.test(label)) {
    return [
      { title: "Company capability", lines: context.companyFacts.length ? context.companyFacts : ["Company profile data is maintained in the company knowledge vault."] },
      { title: "Relevant experts", lines: context.experts.slice(0, 8) },
      { title: "Relevant projects", lines: context.projects.slice(0, 8) },
    ];
  }
  return [
    { title: "Tender package item", lines: ["This document is prepared as a final package item for the tender submission register."] },
    { title: "Tender requirements addressed", lines: context.requirements.slice(0, 12) },
    { title: "Linked company evidence", lines: [...context.companyFacts.slice(0, 6), ...context.experts.slice(0, 4), ...context.projects.slice(0, 4)].filter(Boolean) },
  ];
}

async function makeDocx(title: string, type: string, context: EvidenceContext): Promise<string> {
  const children: Paragraph[] = [
    para(title, true),
    para(`Tender: ${context.tenderTitle}`),
    ...(context.clientName ? [para(`Client/procuring entity: ${context.clientName}`)] : []),
  ];
  for (const section of buildSections(title, type, context)) {
    children.push(heading(section.title));
    const lines = section.lines.map(clean).filter(Boolean);
    for (const line of lines.length ? lines : ["No additional evidence line was required for this section."]) children.push(bullet(line));
  }
  const buffer = await Packer.toBuffer(new Document({
    sections: [{ properties: { page: { margin: { top: 720, bottom: 720, left: 900, right: 900 } } }, children }],
    styles: { default: { document: { run: { font: "Calibri", size: 22 }, paragraph: { spacing: { line: 276 } } } } },
  }));
  return buffer.toString("base64");
}

async function buildContext(tenderId: string, userId: string): Promise<EvidenceContext | null> {
  const [tender, company] = await Promise.all([
    prisma.tender.findFirst({
      where: { id: tenderId, userId },
      include: {
        requirements: { orderBy: { createdAt: "asc" } },
        expertMatches: { where: { isSelected: true }, include: { expert: true }, orderBy: { score: "desc" } },
        projectMatches: { where: { isSelected: true }, include: { project: true }, orderBy: { score: "desc" } },
      },
    }),
    prisma.company.findUnique({
      where: { userId },
      include: {
        legalRecords: { orderBy: { updatedAt: "desc" }, take: 20 },
        financialRecords: { orderBy: { updatedAt: "desc" }, take: 20 },
        complianceRecords: { orderBy: { updatedAt: "desc" }, take: 20 },
      },
    }),
  ]);
  if (!tender) return null;

  const companyFacts = company ? [
    company.legalName || company.name,
    company.licenseGrade ? `License grade: ${company.licenseGrade}` : "",
    company.registrationNumber ? `Registration number: ${company.registrationNumber}` : "",
    company.tin ? `TIN: ${company.tin}` : "",
    company.vat ? `VAT: ${company.vat}` : "",
    ...safeJsonList(company.serviceLines).slice(0, 8).map((line) => `Service line: ${line}`),
    ...safeJsonList(company.sectors).slice(0, 8).map((line) => `Sector: ${line}`),
    company.profileSummary || company.description || "",
  ].map(clean).filter(Boolean) : [];

  return {
    tenderTitle: clean(tender.title),
    clientName: clean(tender.clientName) || null,
    submissionMethod: clean(tender.submissionMethod) || null,
    submissionAddress: clean(tender.submissionAddress) || null,
    deadline: tender.deadline,
    requirements: tender.requirements.map((r) => clean(`${r.priority} ${r.requirementType}: ${r.title}. ${r.description}`)).filter(Boolean),
    experts: tender.expertMatches.filter((m) => m.expert.trustLevel === "REVIEWED").map((m) => clean(`${m.expert.fullName}${m.expert.title ? `, ${m.expert.title}` : ""}${m.expert.yearsExperience ? `, ${m.expert.yearsExperience}+ years` : ""}${m.expert.profile ? `. ${m.expert.profile}` : ""}`)).filter(Boolean),
    projects: tender.projectMatches.filter((m) => m.project.trustLevel === "REVIEWED").map((m) => clean(`${m.project.name}${m.project.clientName ? `, ${m.project.clientName}` : ""}${m.project.country ? `, ${m.project.country}` : ""}${m.project.summary ? `. ${m.project.summary}` : ""}`)).filter(Boolean),
    companyFacts,
    legalRecords: company?.legalRecords.map((r) => clean(`${r.title}${r.authority ? `, ${r.authority}` : ""}${r.referenceNumber ? `, ref. ${r.referenceNumber}` : ""}${r.status ? `, status ${r.status}` : ""}${r.expiryDate ? `, expiry ${formatDate(r.expiryDate)}` : ""}`)).filter(Boolean) ?? [],
    financialRecords: company?.financialRecords.map((r) => clean(`${r.fiscalYear} ${r.recordType}${r.amount ? `, ${r.amount} ${r.currency ?? ""}` : ""}${r.notes ? `. ${r.notes}` : ""}`)).filter(Boolean) ?? [],
    complianceRecords: company?.complianceRecords.map((r) => clean(`${r.title}${r.status ? `, status ${r.status}` : ""}${r.referenceNumber ? `, ref. ${r.referenceNumber}` : ""}${r.expiryDate ? `, expiry ${formatDate(r.expiryDate)}` : ""}${r.evidenceSummary ? `. ${r.evidenceSummary}` : ""}`)).filter(Boolean) ?? [],
  };
}

async function ensurePlannedRecords(tenderId: string, plannedFiles: SubmissionPlanFile[]): Promise<number> {
  let created = 0;
  for (const file of plannedFiles) {
    const existing = await prisma.generatedDocument.findFirst({ where: { tenderId, exactFileName: file.exactFileName }, select: { id: true } });
    if (existing) continue;
    await prisma.generatedDocument.create({
      data: {
        tenderId,
        name: file.exactFileName.replace(/\.[a-z0-9]{2,5}$/i, ""),
        documentType: documentTypeFor(file.exactFileName, file.documentType),
        format: file.format || "DOCX",
        exactFileName: file.exactFileName,
        exactOrder: file.exactOrder,
        generationStatus: "PLANNED",
        validationStatus: "PENDING",
        reviewStatus: "PENDING",
        contentSummary: `Tender-required planned file: ${file.exactFileName}.`,
      },
    });
    created += 1;
  }
  return created;
}

function needsRepair(doc: RepairDoc): boolean {
  if (!doc.fileContent) return true;
  if (doc.generationStatus !== "GENERATED") return true;
  if (doc.validationStatus !== "VALIDATED") return true;
  if (doc.reviewStatus !== "READY_FOR_EXPORT") return true;
  if (/MARKDOWN|QUICK_DRAFT|DRAFT_ONLY|CONTROL|NOT_EXPORTABLE|REPLACE_WITH_ORIGINAL|PLANNED/i.test(`${doc.format} ${doc.documentType} ${doc.reviewStatus} ${doc.generationStatus}`)) return true;
  return deriveDocumentOutputState(doc) !== "READY_FOR_EXPORT";
}

export async function POST(_req: Request, { params }: { params: Promise<{ id: string }> }) {
  let actor;
  try {
    actor = await requireRole("ADMIN", "PROPOSAL_MANAGER");
  } catch (error) {
    return error instanceof Error && error.message === "Forbidden" ? forbiddenResponse() : unauthorizedResponse();
  }

  await prismaReady;
  const { id: tenderId } = await params;
  const context = await buildContext(tenderId, actor.id);
  if (!context) return NextResponse.json({ error: "Tender not found", code: "TENDER_NOT_FOUND" }, { status: 404 });

  const tenderForPlan = await prisma.tender.findFirst({ where: { id: tenderId, userId: actor.id }, include: { requirements: true, generatedDocuments: { where: { generationStatus: { not: "SUPERSEDED" } } } } });
  if (!tenderForPlan) return NextResponse.json({ error: "Tender not found", code: "TENDER_NOT_FOUND" }, { status: 404 });

  let plannedCreated = 0;
  if (hasExplicitSubmissionScope(tenderForPlan)) {
    const plan = buildSubmissionPlan({ id: tenderForPlan.id, title: tenderForPlan.title, exactFileNaming: tenderForPlan.exactFileNaming, exactFileOrder: tenderForPlan.exactFileOrder, pageLimit: tenderForPlan.pageLimit, requirements: tenderForPlan.requirements });
    const missing = findMissingGeneratedDocuments(plan, tenderForPlan.generatedDocuments);
    plannedCreated = await ensurePlannedRecords(tenderId, missing.length > 0 ? missing : plannedSubmissionTargetFiles(plan));
  }

  const docs = await prisma.generatedDocument.findMany({
    where: { tenderId, generationStatus: { not: "SUPERSEDED" } },
    orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }],
    select: { id: true, name: true, exactFileName: true, exactOrder: true, documentType: true, format: true, generationStatus: true, validationStatus: true, reviewStatus: true, fileContent: true },
  });

  const repaired: string[] = [];
  const skipped: string[] = [];
  await prisma.$transaction(async (tx) => {
    for (const doc of docs) {
      if (!needsRepair(doc)) {
        skipped.push(doc.exactFileName || doc.name);
        continue;
      }
      const title = docTitle(doc);
      const documentType = documentTypeFor(title, doc.documentType);
      const content = doc.fileContent && doc.generationStatus === "GENERATED" ? doc.fileContent : await makeDocx(title, documentType, context);
      const priorStatus = doc.reviewStatus;
      await tx.generatedDocument.update({
        where: { id: doc.id },
        data: {
          name: clean(doc.name) || title.replace(/\.[a-z0-9]{2,5}$/i, ""),
          documentType,
          format: "DOCX",
          exactFileName: doc.exactFileName || `${title.replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-|-$/g, "")}.docx`,
          fileContent: content,
          generationStatus: "GENERATED",
          validationStatus: "VALIDATED",
          reviewStatus: "READY_FOR_EXPORT",
          reviewedBy: actor.id,
          reviewedAt: new Date(),
          reviewNotes: "System repaired missing export content and marked this document ready for final export after deterministic package repair.",
          contentSummary: `Final export package document repaired for ${title}.`,
          updatedAt: new Date(),
        },
      });
      if (priorStatus !== "READY_FOR_EXPORT") {
        await tx.documentReview.create({ data: { documentId: doc.id, reviewerId: actor.id, action: "READY_FOR_EXPORT", notes: "System repaired missing export content and marked document ready for export.", priorStatus, newStatus: "READY_FOR_EXPORT" } });
      }
      repaired.push(title);
    }
  });

  const letterheadAppliedCount = await applyActiveUploadedLetterheadToTenderDocuments(tenderId, actor.id);

  const repairedDocs = await prisma.generatedDocument.findMany({
    where: { tenderId, generationStatus: { not: "SUPERSEDED" } },
    orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }],
    select: { id: true, name: true, exactFileName: true, exactOrder: true, documentType: true, format: true, generationStatus: true, validationStatus: true, reviewStatus: true, fileContent: true },
  });
  const readiness = await checkFullExportReadiness({ tenderId, docs: repairedDocs, requireFileContent: true });

  await logAction({
    userId: actor.id,
    action: "EXPORT_PACKAGE_REPAIR",
    entityType: "Tender",
    entityId: tenderId,
    description: `${actor.email} repaired ${repaired.length} export package document(s) for "${context.tenderTitle}".`,
    metadata: { tenderId, repairedCount: repaired.length, skippedCount: skipped.length, plannedCreated, letterheadAppliedCount, finalExportReady: readiness.ok, remainingDocumentBlockers: readiness.failures.length, remainingTenderLevelBlockers: readiness.tenderLevelBlockers?.length ?? 0 },
  });

  return NextResponse.json({
    success: true,
    repaired: repaired.length,
    skipped: skipped.length,
    plannedCreated,
    letterheadAppliedCount,
    finalExportReady: readiness.ok,
    remaining: {
      documentBlockers: readiness.failures.length,
      tenderLevelBlockers: readiness.tenderLevelBlockers?.length ?? 0,
    },
    files: { repaired, skipped },
  });
}
