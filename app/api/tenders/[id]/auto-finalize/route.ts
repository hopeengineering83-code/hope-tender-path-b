// AI/meta trace patterns — reset lastIndex on each use (global flag caveat)
const META_PATTERNS: RegExp[] = [
  /chatgpt|claude|gemini|openai|deepseek|regex fallback|generated by ai|ai provider|ai language model|as an ai|deterministic fallback|benchmark|preparation trace/gi,
  /\b(TODO|TBD|FIXME|PLACEHOLDER)\b/gi,
  /\[(insert[^\]]*|name here|date here|signature here|stamp here|add here|fill in|placeholder)[^\]]*\]/gi,
];

// Targeted rewrite rules for mixed technical/financial phrases.
// These rewrite the offending phrase in place rather than dropping the whole line,
// preserving technical meaning while removing financial leakage.
const TECHNICAL_PHRASE_REWRITES: Array<[RegExp, string]> = [
  [/\bcost\s+control\s+methodology\b/gi, "resource and implementation control methodology"],
  [/\bcost[- ]effective\s+methodology\b/gi, "implementation-focused methodology"],
  [/\bcost[- ]effective\b/gi, "efficient"],
  [/\bbudget[- ]friendly\b/gi, "efficient implementation"],
  [/\bvalue\s+for\s+money\b/gi, "efficient, accountable delivery"],
  [/\bcommercial\s+proposal\s+(?:will\s+be|is|shall\s+be)\s+submitted\s+separately[^.]*\./gi, ""],
  [/\bfinancial\s+proposal\s+(?:will\s+be|is|shall\s+be)\s+submitted\s+separately[^.]*\./gi, ""],
  // "contract value" in project experience context → "project scope"
  [/\bcontract\s+value\b/gi, "project scope"],
  // Currency amounts with numbers
  [/(?:\b(?:USD|ETB|EUR|GBP|Birr|dollar|euro)\s*[0-9][0-9,]*(?:\.\d+)?(?:[KkMmBb](?:illion)?)?\b|\b[0-9][0-9,]*(?:\.\d+)?(?:[KkMmBb](?:illion)?)?\s*(?:USD|ETB|EUR|GBP|Birr|dollar|euro)\b|[$€£]\s*[0-9][0-9,]*(?:\.\d+)?(?:[KkMmBb](?:illion)?)?)/gi, "[scope]"],
  // Rate/fee amounts
  [/\b(?:daily|monthly|hourly|consultancy|professional|service)\s+(?:rate|fee)[:\s]+[$€£]?\s*[0-9][0-9,]*(?:\.\d+)?(?:\s*(?:USD|ETB|EUR|GBP|Birr|dollar|euro))?\b/gi, "[rate on file]"],
  // Standalone percentage fee references
  [/\b(?:fee|charge|commission)\s+of\s+\d+\s*%/gi, "[fee structure on file]"],
  [/\b\d+\s*%\s+(?:fee|charge|commission)\b/gi, "[fee structure on file]"],
];

// Pure financial lines — entire line is a financial header with no technical content worth keeping
const PURE_FINANCIAL_LINE_RX = /^\s*(?:total\s+price|unit\s+price|price\s+schedule|fee\s+schedule|commercial\s+offer|financial\s+proposal|lump\s+sum\s+price?|bill\s+of\s+quantities|BoQ|quoted\s+price|payment\s+schedule|invoice\s+schedule|price\s+breakdown|cost\s+breakdown|budget\s+breakdown)[:\s]/i;

function rewriteFinancialPhrases(sentence: string): string {
  if (PURE_FINANCIAL_LINE_RX.test(sentence)) return "";
  let out = sentence;
  for (const [rx, replacement] of TECHNICAL_PHRASE_REWRITES) {
    out = out.replace(rx, replacement);
  }
  return out.replace(/\s{2,}/g, " ").trim();
}

function cleanLine(line: string, technical: boolean): string {
  let out = line.replace(/[—–]/g, "-").replace(/\s+/g, " ").trim();
  for (const rx of META_PATTERNS) {
    rx.lastIndex = 0;
    out = out.replace(rx, "").trim();
  }
  if (!out) return "";
  if (technical) {
    out = rewriteFinancialPhrases(out);
  }
  return out;
}

async function polishWithAI(text: string, technical: boolean): Promise<string> {
  const prompt = `Rewrite this tender document content to be client-ready, factual, concise, and professional. Remove AI/meta traces and placeholders.${technical ? " Remove pricing/commercial/financial wording from technical envelope content. If a sentence mixes technical content with financial phrasing, keep the technical substance but remove the financial reference. Do not delete entire sections unless they are purely financial." : ""}\n\nCONTENT:\n${text.slice(0, 12000)}`;
  try { return await generateWithFallback(prompt, { systemPrompt: "You are a senior tender editor. Keep facts, improve quality, no inventions." }); } catch { return text; }
}

function isHeadingLine(line: string): boolean {
  const trimmed = line.trim();
  if (!trimmed || trimmed.length > 120) return false;
  if (/[^.!?]:\s*$/.test(trimmed)) return true;
  const letters = trimmed.replace(/[^a-zA-Z]/g, "");
  return letters.length >= 3 && letters === letters.toUpperCase();
}

function isBulletLine(line: string): boolean {
  return /^\s*[-•*]\s+/.test(line) || /^\s*\d+[.)]\s+/.test(line);
}

async function toDocx(title: string, text: string): Promise<string> {
  const rawLines = text.split(/\n+/).map((l) => l.trim()).filter(Boolean);
  const children: Paragraph[] = [
    new Paragraph({
      heading: HeadingLevel.HEADING_1,
      children: [new TextRun({ text: title, bold: true })],
      spacing: { after: 200 },
    }),
  ];
  for (const line of rawLines) {
    if (isHeadingLine(line)) {
      children.push(new Paragraph({
        heading: HeadingLevel.HEADING_2,
        children: [new TextRun({ text: line.replace(/:\s*$/, "").trim(), bold: true })],
        spacing: { before: 200, after: 100 },
      }));
    } else if (isBulletLine(line)) {
      children.push(new Paragraph({
        bullet: { level: 0 },
        children: [new TextRun({ text: line.replace(/^\s*[-•*]\s+/, "").replace(/^\s*\d+[.)]\s+/, "").trim(), size: 22 })],
        spacing: { after: 80 },
      }));
    } else {
      children.push(new Paragraph({
        children: [new TextRun({ text: line, size: 22 })],
        spacing: { after: 120 },
      }));
    }
  }
  const buffer = await Packer.toBuffer(new Document({ sections: [{ children }] }));
  return buffer.toString("base64");
}

// Documents that must never be auto-approved — they require human upload of
// the official tender-issued original or auditor-signed evidence.
// Pattern must stay in sync with isSensitiveFinancialOrLegalDoc in pricing-hygiene.ts.
const SENSITIVE_DOC_RX = /\b(audited|financial\s+statement|tax\s+clearance|vat\s+cert|vat\s+certificate|tin\s+cert|tin\s+certificate|bank\s+statement|bid\s+form|tender\s+form|declaration\s+form|undertaking\s+form|integrity\s+pact|rate\s+card|business\s+license|registration\s+cert|incorporation|annual\s+report)\b/i;

function isSensitiveDocument(doc: { name?: string | null; exactFileName?: string | null; documentType?: string | null }): boolean {
  const label = `${doc.name ?? ""} ${doc.exactFileName ?? ""} ${doc.documentType ?? ""}`;
  return SENSITIVE_DOC_RX.test(label);
}

export async function POST(req: Request, { params }: { params: Promise<{ id: string }> }) {
  let actor;
  try { actor = await requireRole("ADMIN", "PROPOSAL_MANAGER"); } catch (e) { return e instanceof Error && e.message === "Forbidden" ? forbiddenResponse() : unauthorizedResponse(); }
  const requestId = extractRequestId(req);
  const rl = rateLimit(`auto-finalize:${actor.id}`, MUTATION_RATE_LIMIT);
  if (!rl.allowed) return NextResponse.json({ error: "Rate limit exceeded", retryAfter: Math.ceil((rl.resetAt - Date.now()) / 1000) }, { status: 429, headers: { "Retry-After": String(Math.ceil((rl.resetAt - Date.now()) / 1000)) } });
  await prismaReady;
  const { id: tenderId } = await params;
  const tender = await prisma.tender.findFirst({ where: { id: tenderId, userId: actor.id }, include: { requirements: true, generatedDocuments: { where: { generationStatus: { not: "SUPERSEDED" } }, orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }] } } });
  if (!tender) return NextResponse.json({ error: "Tender not found" }, { status: 404 });

  const plan = buildSubmissionPlan(tender);
  const planEmpty = plan.files.length === 0;
  const plannedNames = new Set(plan.files.map((f) => (f.exactFileName ?? "").trim().toLowerCase()));

  // Reconcile old wrong rows: submission rules + outside-plan supersede
  for (const doc of tender.generatedDocuments) {
    const name = (doc.exactFileName ?? doc.name ?? "").toLowerCase();
    if (/submission formatting|packaging rules|submission method|deadline|delivery rules|submission rules/.test(name)) {
      await prisma.generatedDocument.update({ where: { id: doc.id }, data: { format: "CONTROL", reviewStatus: "NOT_EXPORTABLE", reviewNotes: "Submission control metadata; excluded from final export." } });
      continue;
    }
    if (!planEmpty && !plannedNames.has((doc.exactFileName ?? doc.name ?? "").trim().toLowerCase())) {
      await prisma.generatedDocument.update({ where: { id: doc.id }, data: { generationStatus: "SUPERSEDED", validationStatus: "SUPERSEDED", reviewStatus: "NOT_EXPORTABLE", reviewNotes: "Superseded as outside submission plan." } });
    }
  }

  const refreshedAll = await prisma.generatedDocument.findMany({ where: { tenderId, generationStatus: { not: "SUPERSEDED" } }, orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }] });
  const candidates = filterFinalExportCandidateDocuments(refreshedAll as any[]).filter((d) => d.reviewStatus !== "READY_FOR_EXPORT" || d.validationStatus === "FAILED");

  // ── Seven-pass gate: load evidence context once for the whole batch ───────
  const [reviewedExpertCount, reviewedProjectCount] = await Promise.all([
    prisma.tenderExpertMatch.count({ where: { tenderId, isSelected: true, expert: { trustLevel: "REVIEWED" } } }),
    prisma.tenderProjectMatch.count({ where: { tenderId, isSelected: true, project: { trustLevel: "REVIEWED" } } }),
  ]);
  const requiredExpertCount = tender.requirements.filter((r) => r.requirementType === "EXPERT").length;
  const requiredProjectCount = tender.requirements.filter((r) => r.requirementType === "PROJECT_EXPERIENCE").length;
  const totalMandatory = tender.requirements.filter((r) => r.priority === "MANDATORY").length;
  const sourcedMandatory = tender.requirements.filter((r) => r.priority === "MANDATORY" && ((r.sourceConfidence ?? 0) > 0 || (r.sectionReference ?? "").trim().length > 0)).length;

  const batch = candidates.slice(0, 3);
  let processed = 0;
  for (const doc of batch) {
    if (doc.reviewStatus === "REPLACE_WITH_ORIGINAL") continue;
    if (isSensitiveDocument(doc)) continue; // audited statements, bid forms, tax/legal certs — require manual upload
    const fileName = doc.exactFileName ?? doc.name;
    const technical = /technical|methodology|workplan|approach|strategic/i.test(`${fileName} ${doc.documentType ?? ""}`);
    const docMeta = { name: doc.name, exactFileName: doc.exactFileName, documentType: doc.documentType ?? undefined, format: "DOCX" as const };
    const visible = await extractDocxVisibleText(doc.fileContent, fileName);
    const baseText = (visible ?? "").split(/\n+/).map((line) => cleanLine(line, technical)).filter(Boolean).join("\n");
    const polished = await polishWithAI(baseText || `Document: ${fileName}`, technical);
    // Second pass: apply phrase rewrites after AI polish to catch anything AI missed
    const cleaned = polished.split(/\n+/).map((line) => cleanLine(line, technical)).filter(Boolean).join("\n");
    const rebuilt = await toDocx(fileName, cleaned || `${fileName}\nPrepared for submission.`);
    // Re-check pricing leakage on visible text AFTER cleaning — only mark READY_FOR_EXPORT if genuinely clean
    const stillHasPricingLeakage = technical && containsPricingLeakage(cleaned, docMeta);
    const issues = documentHygieneIssues(cleaned, docMeta);
    const hygieneReady = issues.length === 0 && !stillHasPricingLeakage && rebuilt.length > 0;

    // ── Seven-pass gate check ───────────────────────────────────────────────
    const gateEvaluation = evaluateSevenPassForDocument({
      tenderNotes: tender.notes,
      visibleText: cleaned,
      reviewedExpertCount,
      reviewedProjectCount,
      requiredExpertCount,
      requiredProjectCount,
      totalMandatoryRequirements: totalMandatory,
      sourcedMandatoryRequirements: sourcedMandatory,
      documentType: doc.documentType,
      documentName: doc.name,
      exactFileName: doc.exactFileName,
      currentReviewStatus: doc.reviewStatus,
    });
    // A document can only be READY_FOR_EXPORT if both hygiene AND the seven-pass gate allow it.
    const ready = hygieneReady && gateEvaluation.finalApprovalAllowed;

    const priorStatus = doc.reviewStatus;
    const hygieneNotes = hygieneReady ? "" : `hygiene: ${[...issues, ...(stillHasPricingLeakage ? ["pricing leakage detected"] : [])].join("; ")}`;
    const gateNotes = summarizeSevenPassForReviewNotes(gateEvaluation);
    const reviewNotes = ready
      ? `Auto-finalized for print/submission. ${gateNotes}`
      : `Auto-finalized but needs review. ${[hygieneNotes, gateNotes].filter(Boolean).join(" | ")}`;

    await prisma.generatedDocument.update({ where: { id: doc.id }, data: { fileContent: rebuilt, format: "DOCX", generationStatus: "GENERATED", validationStatus: ready ? "VALIDATED" : (gateEvaluation.recommendedValidationStatus === "DRAFT" ? "DRAFT" : "PENDING"), reviewStatus: ready ? "READY_FOR_EXPORT" : "NEEDS_REVIEW", reviewedBy: actor.id, reviewedAt: new Date(), reviewNotes: reviewNotes.slice(0, 4000) } });
    if (ready && priorStatus !== "READY_FOR_EXPORT") await prisma.documentReview.create({ data: { documentId: doc.id, reviewerId: actor.id, action: "READY_FOR_EXPORT", notes: "Auto-finalized for print/submission.", priorStatus, newStatus: "READY_FOR_EXPORT" } });
    processed += 1;
  }

  await applyActiveUploadedLetterheadToTenderDocuments(tenderId, actor.id);
  const finalAll = await prisma.generatedDocument.findMany({ where: { tenderId, generationStatus: { not: "SUPERSEDED" } }, orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }] });
  const finalDocs = filterFinalExportCandidateDocuments(finalAll as any[]);
  const readiness = await checkFullExportReadiness({ tenderId, docs: finalDocs as any[], requireFileContent: false });

  const warning = planEmpty ? "Submission plan empty; outside-plan supersede skipped." : null;
  await logAction({ userId: actor.id, action: "AUTO_FINALIZE_RUN", entityType: "Tender", entityId: tenderId, description: `Auto-finalize processed ${processed} document(s) for ${tender.title}.`, metadata: { tenderId, processed, remaining: Math.max(0, candidates.length - processed), readinessOk: readiness.ok, warning }, requestId });
  return NextResponse.json({ success: true, status: readiness.ok ? "COMPLETED" : "IN_PROGRESS", processedCount: processed, remainingCount: Math.max(0, candidates.length - processed), nextAction: candidates.length - processed > 0 ? "CONTINUE_AUTO_FINALIZE" : "RECHECK_EXPORT_READINESS", readinessOk: readiness.ok, warning });
}
