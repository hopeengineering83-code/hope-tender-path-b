/**
 * Export-gap repair — safe, idempotent DOCX hygiene + status repair.
 *
 * Extracted from /api/tenders/:id/repair-export-gaps so both the HTTP
 * route and the auto-finalize worker (run-next after PROPOSAL_GENERATION)
 * share ONE implementation.
 *
 * What this does:
 *   - For each non-superseded GeneratedDocument:
 *     - Skip if it's manual-only (official originals, PDFs, planned-only,
 *       not-exportable, internal draft/control rows).
 *     - Skip if it's already VALIDATED + READY_FOR_EXPORT with content.
 *     - Otherwise: ensure it has DOCX content (generate a safe placeholder
 *       if empty), clean AI traces / placeholders / pricing leakage from
 *       the DOCX XML, and return mutated bytes to PENDING for the canonical
 *       Document Validator.
 *   - Apply active letterhead branding after repair.
 *
 * What this does NOT do:
 *   - Does not create PDFs (PDFs require finalize-pdf, which renders from
 *     an approved DOCX source).
 *   - Does not touch official-original / REPLACE_WITH_ORIGINAL rows.
 *   - Does not create the Final ZIP (that remains /download?type=zip).
 */

