/**
 * Export-gap repair — safe, idempotent DOCX hygiene + status repair.
 *
 * Extracted from /api/tenders/:id/repair-export-gaps so both the HTTP
 * route and the auto-finalize worker (run-next after PROPOSAL_GENERATION)
 * share ONE implementation.
 *
 * What this does:
 *   - For each non-superseded GeneratedDocument:
 *     - Skip if it's manual-only (official originals, PDFs, planned-only,
 *       not-exportable, internal draft/control rows).
 *     - Skip if it's already VALIDATED + READY_FOR_EXPORT with content.
 *     - Otherwise: ensure it has DOCX content (generate a safe placeholder
 *       if empty), clean AI traces / placeholders / pricing leakage from
 *       the DOCX XML, and return mutated bytes to PENDING for the canonical
 *       Document Validator.
 *   - Apply active letterhead branding after repair.
 *
 * What this does NOT do:
 *   - Does not create PDFs (PDFs require finalize-pdf, which renders from
 *     an approved DOCX source).
 *   - Does not touch official-original / REPLACE_WITH_ORIGINAL rows.
 *   - Does not create the Final ZIP (that remains /download?type=zip).
 */

import { Document, Packer, Paragraph, TextRun } from "docx";
import { prisma } from "../prisma";
import { applyActiveUploadedLetterheadToTenderDocuments } from "./apply-active-letterhead";
import { normalizeStatus } from "./document-output-state";
import { checkFullExportReadiness, documentHygieneIssues, extractDocxVisibleText } from "./export-readiness";
import { containsPricingLeakage } from "./pricing-hygiene";
import { verifiedIntegrityDataFromBase64 } from "./persisted-byte-integrity";
import { generatedDocumentHasContent } from "../generated-document-content";
import { logger } from "../observability";

// ── DOCX XML hygiene cleaner ──────────────────────────────────────────────────
const AI_TRACE_RX = /\b(as an ai|ai language model|chatgpt|claude|gemini|openai|deepseek|prompt|generated by ai|deterministic fallback|bid-team action|submission note:)\b/gi;
const AI_TRACE_TEST_RX = /\b(as an ai|ai language model|chatgpt|claude|gemini|openai|deepseek|prompt|generated by ai|deterministic fallback|bid-team action|submission note:)\b/i;
const PLACEHOLDER_RX = /\[(insert|add|fill|placeholder|todo|tbd|name of|date here|signature here|stamp here)[^\]]*\]/gi;
const PLACEHOLDER_TEST_RX = /\[(insert|add|fill|placeholder|todo|tbd|name of|date here|signature here|stamp here)[^\]]*\]/i;
const PLACEHOLDER_WORD_RX = /\b(TODO|TBD|FIXME|PLACEHOLDER)\b/g;
const PLACEHOLDER_WORD_TEST_RX = /\b(TODO|TBD|FIXME|PLACEHOLDER)\b/i;

const SAFE_REWRITE_MAP: Array<[RegExp, string]> = [
  [/The\s+financial\s+proposal\s+will\s+include[^.]*\./gi, "The proposal demonstrates organizational capacity, relevant experience, staffing readiness, and implementation methodology. Financial submissions, where required, are handled separately according to the tender instructions."],
];

function cleanXmlTextNode(text: string): string {
  let out = text;
  out = out.replace(AI_TRACE_RX, "");
  out = out.replace(PLACEHOLDER_RX, "");
  out = out.replace(PLACEHOLDER_WORD_RX, "");
  for (const [rx, replacement] of SAFE_REWRITE_MAP) {
    out = out.replace(rx, replacement);
  }
  out = out.replace(/\s{3,}/g, "  ").replace(/^\s*[-–—]\s*$/, "").trim();
  return out;
}

function decodeXmlText(value: string): string {
  return value
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'");
}

function encodeXmlText(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function paragraphVisibleText(paragraphXml: string): string {
  return decodeXmlText(
    paragraphXml
      .replace(/<w:tab\s*\/?\s*>/g, " ")
      .replace(/<w:br\s*\/?\s*>/g, " ")
      .replace(/<[^>]+>/g, " "),
  ).replace(/\s+/g, " ").trim();
}

/**
 * The canonical hygiene detector evaluates complete visible sentences, while
 * Word commonly splits a phrase across multiple <w:t> runs for formatting.
 * A run-by-run cleaner therefore cannot reliably remove a prohibited phrase:
 * e.g. "Financial" in one run + " proposal — USD 50,000" in the next.
 */
function textHasCanonicalHygieneRisk(text: string, doc: RepairDoc): boolean {
  if (!text) return false;
  return AI_TRACE_TEST_RX.test(text)
    || PLACEHOLDER_TEST_RX.test(text)
    || PLACEHOLDER_WORD_TEST_RX.test(text)
    || containsPricingLeakage(text, {
      name: doc.name,
      exactFileName: doc.exactFileName,
      documentType: doc.documentType,
      format: doc.format,
    });
}

/**
 * Preserve valid content from a mixed paragraph. Only sentences that trip the
 * same canonical hygiene authority used by export readiness are removed. This
 * avoids the old failure mode where a split-run pricing phrase survived, while
 * also avoiding a destructive whole-paragraph deletion when good technical
 * text shares that paragraph with one unsafe sentence.
 */
function safeParagraphText(text: string, doc: RepairDoc): string {
  const sentences = text.match(/[^.!?]+(?:[.!?]+|$)/g) ?? [text];
  const kept = sentences
    .map((sentence) => sentence.replace(/\s+/g, " ").trim())
    .filter(Boolean)
    .filter((sentence) => !textHasCanonicalHygieneRisk(sentence, doc));
  const safe = kept.join(" ").trim();

  // If the whole paragraph was classified unsafe but sentence splitting failed
  // to isolate the cause, fail closed rather than re-emitting unsafe content.
  if (safe === text.trim() && textHasCanonicalHygieneRisk(text, doc)) return "";
  return safe;
}

function rewriteParagraphVisibleText(paragraphXml: string, safeText: string): string {
  let wrote = false;
  return paragraphXml.replace(
    /(<w:t(?:\s[^>]*)?>)([\s\S]*?)(<\/w:t>)/g,
    (_match, open, _text, close) => {
      if (!wrote && safeText) {
        wrote = true;
        return `${open}${encodeXmlText(safeText)}${close}`;
      }
      return `${open}${close}`;
    },
  );
}

export async function cleanDocxHygieneIssues(base64Content: string, doc: RepairDoc): Promise<string | null> {
  try {
    const buffer = Buffer.from(base64Content, "base64");
    if (buffer.length < 4 || buffer[0] !== 0x50 || buffer[1] !== 0x4b) return null;
    const JSZip = (await import("jszip")).default;
    const zip = await JSZip.loadAsync(buffer);
    const xmlFile = zip.file("word/document.xml");
    if (!xmlFile) return null;
    const xml = await xmlFile.async("string");

    // Repair at paragraph granularity so canonical violations split across
    // multiple Word runs are visible as one sentence. Preserve every safe
    // sentence from a mixed paragraph and rewrite only the visible text runs.
    let cleaned = xml.replace(/<w:p(?:\s[^>]*)?>[\s\S]*?<\/w:p>/g, (paragraphXml) => {
      const visible = paragraphVisibleText(paragraphXml);
      if (!textHasCanonicalHygieneRisk(visible, doc)) return paragraphXml;
      return rewriteParagraphVisibleText(paragraphXml, safeParagraphText(visible, doc));
    });

    // Clean residual single-run AI/placeholder traces. Pricing is not stripped
    // word-by-word: that can leave orphaned amounts and damage safe separation
    // wording. Pricing violations are handled as complete sentences above.
    cleaned = cleaned.replace(/(<w:t(?:\s[^>]*)?>)([\s\S]*?)(<\/w:t>)/g, (_match, open, text, close) => {
      const cleanedText = cleanXmlTextNode(text);
      return `${open}${cleanedText}${close}`;
    });

    if (cleaned === xml) return null;
    zip.file("word/document.xml", cleaned);
    const newBuffer = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
    return newBuffer.toString("base64");
  } catch {
    return null;
  }
}

export type RepairDoc = {
  id: string;
  name: string;
  exactFileName: string | null;
  exactOrder: number | null;
  documentType: string | null;
  format: string | null;
  generationStatus: string;
  validationStatus: string;
  reviewStatus: string;
  reviewNotes?: string | null;
  fileContent: string | null;
  storagePath?: string | null;
};

function clean(value?: string | null): string {
  return (value ?? "")
    .replace(/[\u0000-\u001F\u007F]/g, " ")
    .replace(/\b(TODO|TBD|FIXME|PLACEHOLDER)\b/gi, "")
    .replace(/ChatGPT|Claude|Gemini|as an AI|language model|generated by/gi, "")
    .replace(/[—–]/g, "-")
    .replace(/\s+/g, " ")
    .trim();
}

function fileName(doc: RepairDoc): string {
  return doc.exactFileName || `${clean(doc.name || "Generated document").replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-|-$/g, "") || "Generated-document"}.docx`;
}

function safeTypeFor(name: string, fallback?: string | null): string {
  const label = `${name} ${fallback ?? ""}`.toLowerCase();
  if (/technical|methodology|approach|scope/.test(label)) return "TECHNICAL_PROPOSAL";
  if (/expert|cv|personnel|staff/.test(label)) return "EXPERT_CV_PACKAGE";
  if (/project|experience|reference|portfolio/.test(label)) return "PROJECT_REFERENCE_PACKAGE";
  if (/legal|registration|licen[cs]e|tax|certificate/.test(label)) return "LEGAL_EVIDENCE";
  if (/financial|audited|bank|turnover|capacity/.test(label)) return "FINANCIAL_EVIDENCE";
  if (/submission|deadline|delivery|method|rules/.test(label)) return "SUBMISSION_RULES";
  return fallback || "TENDER_REQUIRED_FILE";
}

function isManualOnly(doc: RepairDoc): string | null {
  const generation = normalizeStatus(doc.generationStatus);
  const validation = normalizeStatus(doc.validationStatus);
  const review = normalizeStatus(doc.reviewStatus);
  const label = `${doc.name ?? ""} ${doc.exactFileName ?? ""} ${doc.documentType ?? ""} ${doc.format ?? ""} ${doc.reviewStatus ?? ""}`;

  if (generation === "SUPERSEDED" || validation === "SUPERSEDED") return "Historical/superseded document; regenerate from the current submission plan instead of repairing.";
  if (review === "REPLACE_WITH_ORIGINAL") return "Tender-issued original form/template required. This is a tender file, not a Company Vault document — repair must not recreate it generically. Company Vault documents are already official after verification.";
  if (review === "NOT_EXPORTABLE") return "Document is marked not exportable. Manual review or original attachment is required.";
  if (generation === "PLANNED") return "Planned-only row. Generate the document through the canonical generation pipeline.";
  if (/QUICK_DRAFT|DRAFT_ONLY|MARKDOWN|CONTROL|PLACEHOLDER/i.test(label)) return "Internal draft/control row. It is not a final submission file.";
  if ((doc.exactFileName ?? "").toLowerCase().endsWith(".pdf") && normalizeStatus(doc.format) !== "PDF") return "PDF output/original is required. Upload the final PDF instead of repairing to DOCX.";
  return null;
}

function needsSafeRepair(doc: RepairDoc): boolean {
  if (isManualOnly(doc)) return false;
  // This pass is DOCX hygiene: it rewrites the row with format "DOCX" and DOCX
  // bytes. A finalized PDF must never enter it.
  //
  // isManualOnly already rejects a `.pdf` file whose format is NOT yet PDF
  // ("upload the final PDF instead of repairing to DOCX"), but that guard is
  // the wrong way round for a PDF that is already correct: a healthy row with
  // exactFileName "X.pdf" and format "PDF" passed it, and — because its
  // reviewNotes carry the auto-finalize marker rather than the
  // `machine:safe-export-repair` one — fell straight through to the repair,
  // which overwrote format to "DOCX". A required PDF rendered by
  // runPdfFinalization was therefore destroyed by the next AUTO_FINALIZE
  // attempt, and the job is durably retried, so the tender ended with no
  // usable required PDF.
  //
  // Skipping (not manualRequired) is the honest classification: there is
  // nothing for a DOCX hygiene pass to repair here, and a healthy final PDF
  // must not be reported as needing manual work.
  if (normalizeStatus(doc.format) === "PDF") return false;
  if (!generatedDocumentHasContent(doc)) return true;
  if (normalizeStatus(doc.generationStatus) !== "GENERATED") return true;
  // Gap 1: the machine repair writes a `machine:safe-export-repair` marker
  // in reviewNotes. A document that already carries this marker has already
  // been content-repaired; it does NOT need another repair pass. Validation
  // status is owned by the Document Validator (Gap 2), not this function —
  // so we do NOT check validationStatus here.
  if (typeof doc.reviewNotes === "string" && doc.reviewNotes.startsWith("machine:safe-export-repair")) return false;
  return true;
}

async function makeSafeDocx(title: string, tenderTitle: string): Promise<string> {
  const buffer = await Packer.toBuffer(new Document({
    sections: [{
      properties: { page: { margin: { top: 720, bottom: 720, left: 900, right: 900 } } },
      children: [
        new Paragraph({ children: [new TextRun({ text: clean(title), bold: true, size: 30 })], spacing: { after: 240 } }),
        new Paragraph({ children: [new TextRun({ text: `Tender: ${clean(tenderTitle)}`, size: 22 })], spacing: { after: 160 } }),
        new Paragraph({ children: [new TextRun({ text: "This file was repaired only as a generated package document. Tender-issued forms are sourced automatically from uploaded Tender Intake files. Company Vault documents are already official.", size: 22 })], spacing: { after: 160 } }),
      ],
    }],
  }));
  return buffer.toString("base64");
}

export type ExportGapRepairResult = {
  repaired: number;
  skipped: number;
  manualRequired: number;
  blockedByHygiene: number;
  letterheadAppliedCount: number;
  finalExportReady: boolean;
  remainingDocumentBlockers: number;
  remainingTenderLevelBlockers: number;
};

/**
 * Run safe export-gap repairs for a tender. Idempotent — documents that
 * are already VALIDATED + READY_FOR_EXPORT are skipped.
 *
 * @param tenderId The tender to repair.
 * @param userId The user performing the repair (for audit + letterhead).
 * @returns Repair result counts.
 */
export async function runExportGapRepair(
  tenderId: string,
  userId: string,
): Promise<ExportGapRepairResult> {
  const tender = await prisma.tender.findFirst({
    where: { id: tenderId, userId },
    select: { id: true, title: true },
  });
  if (!tender) {
    return {
      repaired: 0, skipped: 0, manualRequired: 0, blockedByHygiene: 0,
      letterheadAppliedCount: 0, finalExportReady: false,
      remainingDocumentBlockers: 0, remainingTenderLevelBlockers: 0,
    };
  }

  const docs = await prisma.generatedDocument.findMany({
    where: { tenderId, generationStatus: { not: "SUPERSEDED" } },
    orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }],
    select: { id: true, name: true, exactFileName: true, exactOrder: true, documentType: true, format: true, generationStatus: true, validationStatus: true, reviewStatus: true, reviewNotes: true, fileContent: true, storagePath: true },
  });

  const repaired: string[] = [];
  const skipped: string[] = [];
  const manualRequired: Array<{ id: string; fileName: string; reason: string }> = [];
  const blockedByHygiene: Array<{ name: string; issues: string[] }> = [];

  await prisma.$transaction(async (tx) => {
    for (const doc of docs) {
      const name = fileName(doc);
      const manualReason = isManualOnly(doc);
      if (manualReason) {
        manualRequired.push({ id: doc.id, fileName: name, reason: manualReason });
        continue;
      }
      if (!needsSafeRepair(doc)) {
        skipped.push(name);
        continue;
      }

      const title = clean(doc.exactFileName || doc.name || "Generated document");
      const documentType = safeTypeFor(title, doc.documentType);
      let content = generatedDocumentHasContent(doc) && doc.fileContent ? doc.fileContent : await makeSafeDocx(title, tender.title);
      const visibleText = await extractDocxVisibleText(content, name);
      let hygieneIssues = documentHygieneIssues(visibleText ?? content, { name: doc.name, exactFileName: doc.exactFileName, documentType: doc.documentType ?? undefined, format: doc.format ?? undefined });
      if (hygieneIssues.length > 0) {
        const cleanedContent = await cleanDocxHygieneIssues(content, doc);
        if (cleanedContent) {
          const cleanedText = await extractDocxVisibleText(cleanedContent, name);
          const remainingIssues = documentHygieneIssues(cleanedText ?? cleanedContent, { name: doc.name, exactFileName: doc.exactFileName, documentType: doc.documentType ?? undefined, format: doc.format ?? undefined });
          if (remainingIssues.length === 0) {
            content = cleanedContent;
            hygieneIssues = [];
          } else {
            blockedByHygiene.push({ name, issues: remainingIssues });
            continue;
          }
        } else {
          blockedByHygiene.push({ name, issues: hygieneIssues });
          continue;
        }
      }

      // Any repair that changes fileContent creates a new persisted artifact.
      // Bind the integrity record to the EXACT bytes that will be stored. Leaving
      // the pre-repair hash/length in place makes the canonical validator reject
      // the successfully cleaned DOCX as PERSISTED_BYTE_INTEGRITY_MISMATCH.
      // If the existing bytes are not a DOCX at all, this repair authority must
      // not throw, replace, or bless them. Leave the row untouched so the one
      // canonical validator records the genuine content/integrity failure.
      let integrity: ReturnType<typeof verifiedIntegrityDataFromBase64>;
      try {
        integrity = verifiedIntegrityDataFromBase64({
          fileContent: content,
          filename: name,
          claimedMimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        });
      } catch {
        logger.warn("[export-gap-repair] declined non-DOCX or unverifiable artifact; canonical validation remains authoritative", {
          tenderId,
          documentId: doc.id,
          fileName: name,
        });
        continue;
      }

      await tx.generatedDocument.update({
        where: { id: doc.id },
        data: {
          documentType,
          format: "DOCX",
          exactFileName: name,
          fileContent: content,
          ...integrity,
          generationStatus: "GENERATED",
          // Any byte mutation invalidates the old validation result. Returning
          // the artifact to PENDING does not approve it; it deliberately sends
          // the new exact bytes back through the one canonical validator. This
          // also lets a previously FAILED hygiene document recover on retry.
          validationStatus: "PENDING",
          reviewNotes: "machine:safe-export-repair — DOCX hygiene cleaned (AI traces, placeholders, pricing leakage). Awaiting canonical Document Validator.",
          contentSummary: `Machine export repair completed for ${name}.`,
          updatedAt: new Date(),
        },
      });
      // No DocumentReview row is created — that is a human-review record.
      repaired.push(name);
    }
  });

  const letterheadAppliedCount = await applyActiveUploadedLetterheadToTenderDocuments(tenderId, userId);

  const repairedDocs = await prisma.generatedDocument.findMany({
    where: { tenderId, generationStatus: { not: "SUPERSEDED" } },
    orderBy: [{ exactOrder: "asc" }, { createdAt: "asc" }],
    select: { id: true, name: true, exactFileName: true, exactOrder: true, documentType: true, format: true, generationStatus: true, validationStatus: true, reviewStatus: true, storagePath: true },
  });
  const readiness = await checkFullExportReadiness({ tenderId, docs: repairedDocs as any[], requireFileContent: false });

  logger.info("[export-gap-repair] completed", {
    tenderId,
    repaired: repaired.length,
    skipped: skipped.length,
    manualRequired: manualRequired.length,
    blockedByHygiene: blockedByHygiene.length,
    letterheadAppliedCount,
    finalExportReady: readiness.ok,
  });

  return {
    repaired: repaired.length,
    skipped: skipped.length,
    manualRequired: manualRequired.length,
    blockedByHygiene: blockedByHygiene.length,
    letterheadAppliedCount,
    finalExportReady: readiness.ok,
    remainingDocumentBlockers: readiness.failures.length,
    remainingTenderLevelBlockers: readiness.tenderLevelBlockers?.length ?? 0,
  };
}
