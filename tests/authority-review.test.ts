describe("authority-review — pricing in technical envelope", () => {
  it("pricing content in TECHNICAL document blocks with PRICING_IN_TECHNICAL", () => {
    const doc = makeDoc({
      documentType: "TECHNICAL_PROPOSAL",
      contentSummary: "Unit cost: $500 per day. Bid price includes all taxes.",
    });
    const result = runAuthorityReview([doc], makeManifest(), []);
    assert.equal(result.status, "BLOCKED");
    const blocker = result.blockers.find((b) => b.code === "PRICING_IN_TECHNICAL");
    assert.ok(blocker, "expected PRICING_IN_TECHNICAL blocker");
    assert.equal(blocker?.severity, "CRITICAL");
  });

  it("pricing content in non-TECHNICAL document does not trigger PRICING_IN_TECHNICAL", () => {
    const doc = makeDoc({
      documentType: "FINANCIAL_PROPOSAL",
      contentSummary: "Unit cost: $500 per day. Bid price includes all taxes.",
      exactFileName: "Financial-Proposal.docx",
    });
    const manifest = [{ exactFileName: "Financial-Proposal.docx", documentType: "FINANCIAL_PROPOSAL" }];
    const result = runAuthorityReview([doc], manifest, []);
    const blocker = result.blockers.find((b) => b.code === "PRICING_IN_TECHNICAL");
    assert.equal(blocker, undefined, "should NOT trigger PRICING_IN_TECHNICAL for financial doc");
  });
});

