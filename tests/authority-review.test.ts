import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import {
  runAuthorityReview,
  type DocumentInput,
  type ManifestEntry,
} from "../lib/engine/authority-review";

// ── Helpers ───────────────────────────────────────────────────────────────────

function makeDoc(overrides: Partial<DocumentInput> = {}): DocumentInput {
  return {
    id: "doc-1",
    name: "Technical Proposal",
    documentType: "TECHNICAL_PROPOSAL",
    contentSummary: "A clean technical proposal with methodology and work plan.",
    reviewNotes: null,
    exactFileName: "Technical-Proposal.docx",
    ...overrides,
  };
}

function makeManifest(exactFileName = "Technical-Proposal.docx"): ManifestEntry[] {
  return [{ exactFileName, documentType: "TECHNICAL_PROPOSAL" }];
}

// ── Tests ─────────────────────────────────────────────────────────────────────

describe("authority-review — AI trace detection", () => {
  it("AI trace in contentSummary blocks export with code AI_TRACE", () => {
    const doc = makeDoc({
      contentSummary: "As an AI language model, I cannot provide real project data.",
    });
    const result = runAuthorityReview([doc], makeManifest(), []);
    assert.equal(result.status, "BLOCKED");
    const blocker = result.blockers.find((b) => b.code === "AI_TRACE");
    assert.ok(blocker, "expected AI_TRACE blocker");
    assert.equal(blocker?.severity, "CRITICAL");
  });

  it("ChatGPT mention triggers AI_TRACE blocker", () => {
    const doc = makeDoc({ contentSummary: "Generated by ChatGPT for testing." });
    const result = runAuthorityReview([doc], makeManifest(), []);
    const blocker = result.blockers.find((b) => b.code === "AI_TRACE");
    assert.ok(blocker, "expected AI_TRACE blocker");
  });
});

