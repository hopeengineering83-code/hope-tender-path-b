// Tests for the export-gap repair hygiene gate.
//
// Verifies that:
// 1. The old "No price leakage" boilerplate triggers the hygiene check (regression proof).
// 2. The new "Submission envelope compliance" section passes the hygiene check.
// 3. documentHygieneIssues correctly detects AI traces, placeholders, and pricing leakage.
// 4. USD/ETB amounts in a technical context are still caught.
// 5. finalExportReady=false shape when hygiene blockers remain.

import { describe, it } from "node:test";
import { strict as assert } from "node:assert";

// ─── Inline documentHygieneIssues (mirrors export-readiness.ts) ──────────────

function looksLikePlainText(value: string): boolean {
  if (!value || value.length > 1_000_000) return false;
  const sample = value.slice(0, 2000);
  const nonPrintable = sample.replace(/[\t\n\r\x20-\x7E]/g, "").length;
  const printableRatio = 1 - nonPrintable / Math.max(sample.length, 1);
  const alphaCount = (sample.match(/[a-zA-Z]/g) ?? []).length;
  return printableRatio > 0.92 && alphaCount >= 20;
}

function documentHygieneIssues(text: string | null | undefined): string[] {
  if (!text || !looksLikePlainText(text)) return [];
  const issues: string[] = [];
  if (/\b(as an ai|ai language model|chatgpt|claude|gemini|prompt|generated by ai|deterministic fallback|bid-team action|submission note:)\b/i.test(text)) {
    issues.push("AI/meta-preparation trace text is present");
  }
  if (/\[(insert|add|fill|placeholder|todo|tbd|name of|date here|signature here|stamp here)[^\]]*\]/i.test(text) || /\b(TODO|TBD|FIXME|PLACEHOLDER)\b/i.test(text)) {
    issues.push("Placeholder or unresolved drafting instruction is present");
  }
  if (/\b(?:EUR|USD|ETB|GBP|Birr|fee|rate|unit price|total price|financial proposal|price schedule)\b/i.test(text) && /\btechnical\b/i.test(text)) {
    issues.push("Possible financial/pricing language appears in a technical document");
  }
  return issues;
}

// ─── Old financial branch (regression proof) ─────────────────────────────────

function oldFinancialSections(): Array<{ title: string; lines: string[] }> {
  return [
    { title: "Financial evidence", lines: ["Financial records available in the company knowledge vault are referenced for this tender package item."] },
    { title: "No price leakage", lines: ["This technical package item does not include fee amounts, rates, unit prices, or financial offer values unless the tender explicitly requires a combined submission."] },
  ];
}

// ─── New financial branch ─────────────────────────────────────────────────────

function newFinancialSections(financialRecords: string[]): Array<{ title: string; lines: string[] }> {
  return [
    {
      title: "Financial evidence",
      lines: financialRecords.length ? financialRecords : ["Financial records available in the company knowledge vault are referenced for this tender package item."],
    },
    {
      title: "Submission envelope compliance",
      lines: ["This submission package is prepared in accordance with the tender's envelope separation requirements. Financial information is presented only in designated financial submission components."],
    },
  ];
}

function sectionsText(sections: Array<{ title: string; lines: string[] }>): string {
  return sections.map((s) => `${s.title} ${s.lines.join(" ")}`).join(" ");
}

// ─── Tests: documentHygieneIssues — AI trace detection ───────────────────────

describe("documentHygieneIssues — AI trace detection", () => {
  it("flags 'as an AI' trace", () => {
    const issues = documentHygieneIssues("This document was prepared as an AI language model output for submission.");
    assert.ok(issues.some((i) => i.includes("AI/meta-preparation")), `Expected AI trace issue, got: ${JSON.stringify(issues)}`);
  });

  it("flags 'ChatGPT' mention", () => {
    const issues = documentHygieneIssues("Generated by ChatGPT from the following prompt for this project.");
    assert.ok(issues.some((i) => i.includes("AI/meta-preparation")));
  });

  it("flags 'Claude' as an AI trace", () => {
    const issues = documentHygieneIssues("This document was assembled using Claude to summarize the relevant evidence.");
    assert.ok(issues.some((i) => i.includes("AI/meta-preparation")));
  });

  it("does not flag a clean technical document", () => {
    const issues = documentHygieneIssues("Supervision and quality control is ensured by senior engineers with 10+ years of experience in civil construction.");
    assert.deepEqual(issues, []);
  });

  it("returns empty array for null input", () => {
    assert.deepEqual(documentHygieneIssues(null), []);
  });

  it("returns empty array for empty string", () => {
    assert.deepEqual(documentHygieneIssues(""), []);
  });
});

// ─── Tests: documentHygieneIssues — placeholder detection ────────────────────

describe("documentHygieneIssues — placeholder detection", () => {
  it("flags TODO keyword", () => {
    const issues = documentHygieneIssues("TODO: insert company registration number here in the document for review.");
    assert.ok(issues.some((i) => i.includes("Placeholder")));
  });

  it("flags [insert name here] style placeholder", () => {
    const issues = documentHygieneIssues("Signed by [insert name here] on [date here] at the submission office.");
    assert.ok(issues.some((i) => i.includes("Placeholder")));
  });

  it("flags PLACEHOLDER keyword", () => {
    const issues = documentHygieneIssues("Company registration number: PLACEHOLDER — update before submission.");
    assert.ok(issues.some((i) => i.includes("Placeholder")));
  });

  it("does not flag a properly filled document", () => {
    const issues = documentHygieneIssues("Company registration number: ETH-123456. Licensed by the Ethiopian Construction Authority.");
    assert.deepEqual(issues, []);
  });
});

// ─── Tests: documentHygieneIssues — pricing in technical documents ────────────

describe("documentHygieneIssues — pricing in technical context", () => {
  it("flags USD amounts in a technical document", () => {
    const issues = documentHygieneIssues("The technical proposal includes a total budget of USD 500,000 for the design services component.");
    assert.ok(issues.some((i) => i.includes("financial/pricing language")), `Expected pricing issue, got: ${JSON.stringify(issues)}`);
  });

  it("flags 'fee' combined with 'technical'", () => {
    const issues = documentHygieneIssues("Technical submission shall not include the consulting fee or rate schedule in this envelope.");
    assert.ok(issues.some((i) => i.includes("financial/pricing language")));
  });

  it("flags ETB amounts when 'technical' is also present", () => {
    const issues = documentHygieneIssues("The technical budget allocation of ETB 2,500,000 covers supervision and quality control.");
    assert.ok(issues.some((i) => i.includes("financial/pricing language")));
  });

  it("does not flag ETB amounts when 'technical' is absent", () => {
    // Financial document: has ETB but no 'technical' → should not trigger
    const issues = documentHygieneIssues("The audited financial statement shows ETB 2,500,000 in revenue for fiscal year 2023.");
    assert.deepEqual(issues.filter((i) => i.includes("financial/pricing")), [], `Unexpected issues: ${JSON.stringify(issues)}`);
  });

  it("does not flag clean financial evidence without 'technical' context", () => {
    const issues = documentHygieneIssues("Audited financial statements for 2022 and 2023 confirm the company meets the minimum turnover requirements.");
    assert.deepEqual(issues, []);
  });
});

// ─── Tests: buildSections financial branch boilerplate fix ───────────────────

describe("buildSections financial branch — boilerplate regression", () => {
  it("old 'No price leakage' boilerplate triggers hygiene (regression proof)", () => {
    const text = sectionsText(oldFinancialSections());
    const issues = documentHygieneIssues(text);
    assert.ok(
      issues.some((i) => i.includes("financial/pricing language")),
      `Old boilerplate must trigger pricing hygiene. Got: ${JSON.stringify(issues)}`,
    );
  });

  it("new 'Submission envelope compliance' section passes hygiene with empty records", () => {
    const text = sectionsText(newFinancialSections([]));
    const issues = documentHygieneIssues(text);
    assert.deepEqual(
      issues.filter((i) => i.includes("financial/pricing")),
      [],
      `Unexpected pricing issues in new boilerplate: ${JSON.stringify(issues)}`,
    );
  });

  it("new financial sections with fallback content contain no AI traces", () => {
    const text = sectionsText(newFinancialSections([]));
    const issues = documentHygieneIssues(text);
    assert.deepEqual(
      issues.filter((i) => i.includes("AI/meta")),
      [],
      `Unexpected AI trace issues: ${JSON.stringify(issues)}`,
    );
  });

  it("new financial sections contain no placeholders", () => {
    const text = sectionsText(newFinancialSections([]));
    const issues = documentHygieneIssues(text);
    assert.deepEqual(
      issues.filter((i) => i.includes("Placeholder")),
      [],
      `Unexpected placeholder issues: ${JSON.stringify(issues)}`,
    );
  });

  it("compliance section title 'Submission envelope compliance' contains no pricing keywords", () => {
    const PRICING = /\b(?:EUR|USD|ETB|GBP|Birr|fee|rate|unit price|total price|financial proposal|price schedule)\b/i;
    const complianceSection = newFinancialSections([])[1];
    assert.ok(!PRICING.test(complianceSection.title), `Pricing keyword in section title: "${complianceSection.title}"`);
  });

  it("compliance section body contains no pricing keywords", () => {
    const PRICING = /\b(?:EUR|USD|ETB|GBP|Birr|fee|rate|unit price|total price|financial proposal|price schedule)\b/i;
    const complianceSection = newFinancialSections([])[1];
    const body = complianceSection.lines.join(" ");
    assert.ok(!PRICING.test(body), `Pricing keyword in compliance body: "${body}"`);
  });

  it("compliance section body does not contain 'technical'", () => {
    const complianceSection = newFinancialSections([])[1];
    const body = complianceSection.lines.join(" ");
    assert.ok(!/\btechnical\b/i.test(body), `Unexpected 'technical' in compliance body: "${body}"`);
  });

  it("full new financial sections text passes all hygiene checks", () => {
    const text = sectionsText(newFinancialSections([]));
    const issues = documentHygieneIssues(text);
    assert.deepEqual(issues, [], `Expected no hygiene issues, got: ${JSON.stringify(issues)}`);
  });
});

// ─── Tests: hygiene gate — finalExportReady shape ────────────────────────────

describe("hygiene gate — finalExportReady shape", () => {
  it("finalExportReady is false when blockedByHygiene > 0", () => {
    const result = {
      repaired: 2,
      skipped: 0,
      blockedByHygiene: 1,
      finalExportReady: false,
      remaining: { documentBlockers: 1, tenderLevelBlockers: 0 },
    };
    assert.equal(result.finalExportReady, false);
    assert.ok(result.blockedByHygiene > 0);
  });

  it("finalExportReady is true when blockedByHygiene is 0 and no other blockers", () => {
    const result = {
      repaired: 3,
      skipped: 0,
      blockedByHygiene: 0,
      finalExportReady: true,
      remaining: { documentBlockers: 0, tenderLevelBlockers: 0 },
    };
    assert.equal(result.finalExportReady, true);
    assert.equal(result.blockedByHygiene, 0);
  });

  it("hygiene blockers prevent export even when all other statuses are repaired", () => {
    // Simulates: 2 docs repaired OK, 1 blocked by hygiene → finalExportReady must be false
    const repairedCount = 2;
    const blockedByHygieneCount = 1;
    // In the route, blockedByHygiene docs are not marked READY_FOR_EXPORT,
    // so checkFullExportReadiness would still see them as not ready
    const documentBlockers: number = blockedByHygieneCount;
    assert.ok(documentBlockers > 0, "Hygiene blocker creates document blocker");
    assert.equal(repairedCount + blockedByHygieneCount, 3);
  });

  it("hygieneBlockers array in response contains doc name and issues", () => {
    const hygieneBlockers = [
      { name: "Technical-Proposal.docx", issues: ["AI/meta-preparation trace text is present"] },
    ];
    assert.equal(hygieneBlockers.length, 1);
    assert.ok(hygieneBlockers[0].issues.length > 0);
    assert.equal(typeof hygieneBlockers[0].name, "string");
  });

  it("response files.blockedByHygiene is an array of document names", () => {
    const blockedByHygiene = [
      { name: "Financial-Evidence.docx", issues: ["Possible financial/pricing language appears in a technical document"] },
    ];
    const responseFilesBlockedByHygiene = blockedByHygiene.map((b) => b.name);
    assert.deepEqual(responseFilesBlockedByHygiene, ["Financial-Evidence.docx"]);
  });
});
