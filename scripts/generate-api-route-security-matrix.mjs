import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const API_DIR = path.join(ROOT, 'app', 'api');
const OUT = path.join(ROOT, 'docs', 'audits', 'api-route-security-matrix.md');

function walk(dir) {
  return readdirSync(dir)
    .flatMap((name) => {
      const full = path.join(dir, name);
      return statSync(full).isDirectory() ? walk(full) : [full];
    })
    .filter((file) => file.endsWith(`${path.sep}route.ts`))
    .sort();
}

function rel(file) {
  return path.relative(ROOT, file).replaceAll(path.sep, '/');
}

function routePath(file) {
  const relative = rel(file).replace(/^app\/api/, '/api').replace(/\/route\.ts$/, '');
  return relative === '/api' ? '/api' : relative;
}

function exportedMethods(source) {
  const patterns = [
    /export\s+async\s+function\s+(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\b/g,
    /export\s+function\s+(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\b/g,
    /export\s+const\s+(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\b/g
  ];
  const methods = [];
  for (const pattern of patterns) {
    for (const match of source.matchAll(pattern)) {
      methods.push(match[1]);
    }
  }
  return methods.length ? [...new Set(methods)].sort() : ['UNKNOWN'];
}

function authPolicy(source, route) {
  if (source.includes('handleSecureUpload')) return 'Role-gated via shared secure upload handler';
  if (source.includes('handleUploadFirstTender')) return 'Role-gated via shared upload-first handler';
  if (source.includes('requireRole')) return 'Role-gated (`requireRole`)';
  if (source.includes('requireUser')) return 'Authenticated user (`requireUser`)';
  if (source.includes('getSession')) return 'Session-gated (`getSession`)';
  if (source.includes('ADMIN_SECRET')) return 'Admin-secret gated';
  if (source.includes('CRON_SECRET')) return 'Cron-secret gated';
  if (source.includes('AI_JOBS_WORKER_SECRET') || source.includes('WORKER_SECRET')) return 'Worker-secret gated';
  if (route.includes('/share/')) return 'Bearer share-token gated';
  if (['/api/health', '/api/version', '/api/ai/health'].includes(route)) return 'Public diagnostic (no sensitive payload)';
  if (route.startsWith('/api/auth/')) return 'Public auth endpoint (input-limited)';
  if (route === '/api/locale') return 'Public preference endpoint';
  return 'REVIEW_REQUIRED';
}

function rateLimitPolicy(source) {
  if (source.includes('rateLimitPersistent')) return 'Persistent rate limit';
  if (source.includes('rateLimit(')) return 'In-memory rate limit';
  if (source.includes('Retry-After')) return 'Rate-limit response path present';
  return 'None detected / not applicable';
}

function tenantScope(source) {
  if (source.includes('handleSecureUpload') || source.includes('handleUploadFirstTender')) return 'Tenant/user scoped in shared upload handler';
  if (source.includes('requireRole') || source.includes('requireUser') || source.includes('getSession')) {
    // tenderId, companyId, findFirst etc are NOT ownership proof.
    return 'Static inventory and auth signals — not authorization proof.';
  }
  return 'Not tenant data or token/secret scoped';
}

function sensitiveFields(source) {
  const fields = [];
  if (source.includes('fileContent')) fields.push('fileContent');
  if (source.includes('extractedText')) fields.push('extractedText');
  if (source.includes('passwordHash')) fields.push('passwordHash');
  if (source.includes('proposal') || source.includes('GeneratedDocument')) fields.push('proposal/document body risk');
  return fields.length ? fields.join(', ') : 'No obvious large/sensitive field marker';
}

const files = walk(API_DIR);
const rows = files.flatMap((file) => {
  const source = readFileSync(file, 'utf8');
  const route = routePath(file);
  const methods = exportedMethods(source);

  return methods.map((method) => {
    // Detect method-specific auth if possible, otherwise fall back to file-wide
    // This is a heuristic; deep analysis of handlers would require a proper parser.
    // For now, we keep it file-wide but separate the rows to avoid "inheritance" claim.
    return {
      file: rel(file),
      route,
      method,
      auth: authPolicy(source, route),
      tenant: tenantScope(source),
      rateLimit: rateLimitPolicy(source),
      sensitive: sensitiveFields(source),
    };
  });
});

const reviewRequired = rows.filter((row) => row.auth === 'REVIEW_REQUIRED');
const lines = [
  '# API Route Security Matrix',
  '',
  '> Generated by `node scripts/generate-api-route-security-matrix.mjs`. Do not edit route rows manually; update the generator or route code instead.',
  '',
  `Generated route handlers: **${rows.length}**`,
  `Routes requiring manual auth classification: **${reviewRequired.length}**`,
  '',
  '## Policy',
  '',
  '- Every `app/api/**/route.ts` handler must appear in this matrix.',
  '- Every handler must have an explicit auth classification; `REVIEW_REQUIRED` is a failing state in tests.',
  '- Tenant data routes must be user/company/tender scoped or protected by a bearer/secret/public diagnostic policy.',
  '- Routes touching `fileContent`, `extractedText`, generated proposal bodies, or secrets need additional response-shape scrutiny.',
  '',
  '## Matrix',
  '',
  '| Route | Method | Auth classification | Tenant scope | Rate limit | Sensitive-field markers | File |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| \`${r.route}\` | ${r.method} | ${r.auth} | ${r.tenant} | ${r.rateLimit} | ${r.sensitive} | \`${r.file}\` |`),
  '',
];

const checkMode = process.argv.includes('--check');

if (checkMode) {
  const existing = readFileSync(OUT, 'utf8');
  if (existing !== lines.join('\n')) {
    console.error('FAIL: Committed API security matrix is stale. Run `node scripts/generate-api-route-security-matrix.mjs` to update.');
    process.exit(1);
  }
  console.log('✓ API security matrix is up to date.');
} else {
  writeFileSync(OUT, lines.join('\n'));
  console.log(`Wrote ${rel(OUT)} with ${rows.length} handlers.`);
}
if (reviewRequired.length > 0) {
  console.error(`Routes needing classification:\n${reviewRequired.map((r) => `- ${r.file}`).join('\n')}`);
  process.exitCode = 1;
}
